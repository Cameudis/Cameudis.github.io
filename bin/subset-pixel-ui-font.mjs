#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_FONT = join(
  ROOT,
  'assets/fonts/fusion-pixel-font-10px-proportional-otf.woff2-v2025.10.20',
  'fusion-pixel-10px-proportional-zh_hans.otf.woff2'
);
const OUTPUT_FONT = join(ROOT, 'assets/fonts/fusion-pixel-10px-ui.woff2');
const OUTPUT_SCSS = join(ROOT, '_sass/minima/_pixel-ui-font.scss');
const OUTPUT_DATA = join(ROOT, '_data/pixel_ui_font.yml');
const CHECK_ONLY = process.argv.includes('--check');

// These sources contain site chrome and fixed component copy. Posts and the
// diary are deliberately excluded so arbitrary content keeps using system CJK.
const TEXT_SOURCES = [
  '_config.yml',
  '_includes',
  '_layouts',
  '_sass/minima',
  'assets/js',
  'link.md'
];
const TEXT_EXTENSIONS = new Set(['.html', '.js', '.md', '.scss', '.yml']);
const BASE_UNICODE_RANGES = [
  'U+0020-007E',
  'U+00A0-00FF',
  'U+2000-206F',
  'U+2190-21FF',
  'U+2500-26FF',
  'U+FF01-FF65'
];

function collectFiles(path) {
  if (!existsSync(path)) return [];
  if (!statSync(path).isDirectory()) return [path];
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    const child = join(path, entry.name);
    return entry.isDirectory() ? collectFiles(child) : [child];
  });
}

function collectLiteralCodePoints() {
  const points = new Set();
  for (const source of TEXT_SOURCES) {
    for (const file of collectFiles(join(ROOT, source))) {
      if (!TEXT_EXTENSIONS.has(extname(file))) continue;
      for (const character of readFileSync(file, 'utf8')) {
        const point = character.codePointAt(0);
        if (point > 0xff && !/\s/u.test(character)) points.add(point);
      }
    }
  }
  return [...points].sort((left, right) => left - right);
}

function writeIfChanged(path, contents) {
  const next = Buffer.isBuffer(contents) ? contents : Buffer.from(contents);
  if (existsSync(path) && readFileSync(path).equals(next)) return false;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next);
  return true;
}

const literalCodePoints = collectLiteralCodePoints();
const unicodes = [
  ...BASE_UNICODE_RANGES,
  ...literalCodePoints.map((point) => `U+${point.toString(16).toUpperCase()}`)
].join(',');
const tempDirectory = mkdtempSync(join(tmpdir(), 'pixel-ui-font-'));
const tempFont = join(tempDirectory, 'fusion-pixel-10px-ui.woff2');

try {
  const subset = spawnSync(
    'python3',
    [
      '-m',
      'fontTools.subset',
      SOURCE_FONT,
      `--output-file=${tempFont}`,
      '--flavor=woff2',
      `--unicodes=${unicodes}`
    ],
    { cwd: ROOT, encoding: 'utf8' }
  );

  if (subset.status !== 0) {
    const detail = (subset.stderr || subset.stdout || 'unknown FontTools error').trim();
    throw new Error(`Unable to generate the pixel UI font:\n${detail}`);
  }

  const font = readFileSync(tempFont);
  const version = createHash('sha256').update(font).digest('hex').slice(0, 12);
  const generatedScss = `// Generated by bin/subset-pixel-ui-font.mjs. Do not edit manually.\n` +
    `@font-face {\n` +
    `  font-family: "FusionPixelUI";\n` +
    `  src: url('fonts/fusion-pixel-10px-ui.woff2?v=${version}') format("woff2");\n` +
    `  font-display: swap;\n` +
    `}\n`;
  const generatedData = `# Generated by bin/subset-pixel-ui-font.mjs. Do not edit manually.\n` +
    `version: "${version}"\n`;

  const expected = [
    [OUTPUT_FONT, font],
    [OUTPUT_SCSS, generatedScss],
    [OUTPUT_DATA, generatedData]
  ];

  if (CHECK_ONLY) {
    const stale = expected
      .filter(([path, contents]) => {
        const next = Buffer.isBuffer(contents) ? contents : Buffer.from(contents);
        return !existsSync(path) || !readFileSync(path).equals(next);
      })
      .map(([path]) => path.slice(ROOT.length + 1));
    if (stale.length > 0) {
      throw new Error(`Pixel UI font outputs are stale: ${stale.join(', ')}`);
    }
  } else {
    expected.forEach(([path, contents]) => writeIfChanged(path, contents));
  }

  const sizeKiB = (font.length / 1024).toFixed(1);
  console.log(
    `${CHECK_ONLY ? 'Checked' : 'Generated'} pixel UI font: ` +
    `${literalCodePoints.length} source-specific characters, ${sizeKiB} KiB, v=${version}`
  );
} finally {
  rmSync(tempDirectory, { recursive: true, force: true });
}
